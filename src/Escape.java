public class Escape {
    public static void main(String[] args) {
        System.out.println("Hello..\"Neel\" ");
        System.out.println("Hello..\'Neel\'");
        System.out.println("Hello..\\Neel\\");
        System.out.println("Hello..\nNeel");
        System.out.println("Hello..\tNeel");
        System.out.println("Hello..\bNeel");
    }
}
