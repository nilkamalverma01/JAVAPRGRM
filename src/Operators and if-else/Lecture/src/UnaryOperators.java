public class UnaryOperators {
    public static void main(String[] args) {
        int x = 5;
        int y = -x;
        int z = -y;
        System.out.println(z + "\n");

        int a = 10;
        a++;
        System.out.println(a);
        ++a;
        System.out.println(a + "\n");

        int m = 5;
        m++;
        System.out.println(m);
        ++m;
        System.out.println(m + "\n");

        int p = 10;
        p--;
        System.out.println(p);
        --p;
        System.out.println(p);
    }
}
